// Simulate browser events at their boundary without creating production data or installing software.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { runInNewContext } from 'node:vm';
const require = createRequire(new URL('../frontend/package.json', import.meta.url));
const ts = require('typescript');
const source = ts.transpileModule(readFileSync(new URL('../frontend/src/appLifecycle.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
let checks = 0;
const check = (label, ok) => { assert.ok(ok, label); console.log(`PASS ${++checks}: ${label}`); };
const tick = async () => { for (let i = 0; i < 8; i++) await Promise.resolve(); };
function setup({ secure = true, controlled = true, standalone = false, failRegistration = false } = {}) {
  const window = new EventTarget(), document = new EventTarget(), media = new EventTarget(), sw = new EventTarget(), registration = new EventTarget(), worker = new EventTarget();
  let reloads = 0, prompts = 0, state, posted = [], timers = new Map(), counter = 0;
  media.matches = standalone;
  Object.assign(window, { isSecureContext: secure, matchMedia: () => media, location: { reload: () => reloads++ } });
  document.visibilityState = 'visible';
  worker.state = 'installed'; worker.postMessage = message => posted.push(message);
  registration.waiting = null; registration.installing = null; registration.update = async () => {};
  sw.controller = controlled ? {} : null;
  sw.register = async () => { if (failRegistration) throw Error('registration'); return registration; };
  const navigator = { serviceWorker: sw, onLine: true }, exports = {};
  runInNewContext(source, { exports, window, document, navigator, WeakSet, Date, setInterval: () => 1, clearInterval: () => {}, setTimeout: fn => { const id = ++counter; timers.set(id, fn); return id; }, clearTimeout: id => timers.delete(id) });
  state = exports.initialAppState();
  const client = exports.createAppLifecycle(value => { state = value; });
  const installEvent = outcome => {
    const e = new Event('beforeinstallprompt', { cancelable: true });
    e.prompt = async () => { prompts++; }; e.userChoice = Promise.resolve({ outcome }); window.dispatchEvent(e); return e;
  };
  return { exports, window, media, sw, registration, worker, navigator, client, installEvent, timers, get state() { return state; }, get reloads() { return reloads; }, get prompts() { return prompts; }, get posted() { return posted; } };
}
let s = setup(); await tick();
const e = s.installEvent('dismissed');
check('浏览器安装事件变为可安装状态', e.defaultPrevented && s.state.install === 'available');
await s.client.install(); await s.client.install();
check('取消安装显示中文反馈，提示只消费一次', s.prompts === 1 && s.state.install === 'manual' && s.state.installMessage.includes('取消'));
s.installEvent('accepted'); await s.client.install();
check('接受提示不冒充安装完成', s.state.install === 'accepted');
s.window.dispatchEvent(new Event('appinstalled'));
check('收到安装完成事件才显示已安装', s.state.install === 'installed'); s.client.dispose();
s = setup(); await tick();
const failure = s.installEvent('accepted'); failure.prompt = async () => { throw Error('browser failure'); };
await s.client.install();
check('安装失败返回中文菜单引导', s.state.install === 'manual' && s.state.installMessage.includes('浏览器菜单')); s.client.dispose();
s = setup({ standalone: true }); check('独立窗口识别为已安装', s.state.install === 'installed'); s.client.dispose();
s = setup({ secure: false }); check('非安全地址不误导安装或更新', s.state.install === 'unavailable' && s.state.update === 'unavailable'); s.client.dispose();
check('iPad 桌面 UA 使用 Safari 步骤', s.exports.devicePlatform('Mozilla Macintosh', 5) === 'ios');
check('安卓和电脑分别提供引导', s.exports.devicePlatform('Android', 1) === 'android' && s.exports.devicePlatform('Windows NT', 0) === 'desktop');
s = setup(); s.registration.waiting = s.worker; await tick();
check('待安装新版仅提示，不刷新或激活', s.state.update === 'ready' && s.reloads === 0 && s.posted.length === 0);
s.registration.update = async () => { throw Error('network'); }; await s.client.checkForUpdate();
check('检查失败不丢失已经准备好的更新', s.state.update === 'ready' && s.state.updateMessage.includes('失败'));
s.navigator.onLine = false; await s.client.checkForUpdate();
check('断网检查给中文原因且不激活', s.state.update === 'ready' && s.state.updateMessage.includes('没有网络') && s.posted.length === 0);
s.client.applyUpdate(); check('确认后才发送激活消息', s.state.update === 'applying' && s.posted[0].type === 'ACTIVATE_UPDATE' && s.reloads === 0);
s.sw.dispatchEvent(new Event('controllerchange')); check('本人确认的更新控制页面后才刷新', s.reloads === 1); s.client.dispose();
s = setup(); await tick(); s.sw.dispatchEvent(new Event('controllerchange'));
check('其他标签更新不强制刷新当前页', s.reloads === 0 && s.state.update === 'reload');
s.client.applyUpdate(); check('其他标签更新后本人确认才刷新', s.reloads === 1); s.client.dispose();
s = setup({ controlled: false }); await tick(); s.sw.controller = {}; s.sw.dispatchEvent(new Event('controllerchange'));
check('首次取得控制不提醒更新或刷新', s.reloads === 0 && s.state.update === 'idle'); s.client.dispose();
s = setup(); await tick(); s.registration.installing = s.worker; s.worker.state = 'installing'; s.registration.dispatchEvent(new Event('updatefound'));
s.registration.waiting = s.worker; s.worker.state = 'installed'; s.worker.dispatchEvent(new Event('statechange'));
check('后台下载完成只提示待更新', s.state.update === 'ready' && s.reloads === 0); s.client.applyUpdate();
for (const fn of [...s.timers.values()]) fn();
check('激活超时回到可重试状态', s.state.update === 'ready' && s.state.updateMessage.includes('尚未完成') && s.reloads === 0);
s.sw.dispatchEvent(new Event('controllerchange'));
check('超时后延迟激活也不自动刷新', s.state.update === 'reload' && s.reloads === 0); s.client.dispose();
s = setup(); await tick(); await s.client.checkForUpdate();
check('无新版检查显示中文结果', s.state.update === 'idle' && s.state.updateMessage.includes('暂未发现'));
const previous = s.state; s.client.dispose(); s.installEvent('accepted'); s.window.dispatchEvent(new Event('appinstalled')); s.sw.dispatchEvent(new Event('controllerchange'));
check('卸载组件后监听不再修改状态或刷新', s.state === previous && s.reloads === 0);
s = setup({ failRegistration: true }); await tick();
check('注册失败提供中文错误', s.state.update === 'error' && s.state.updateMessage.includes('联网')); s.client.dispose();
console.log(`${checks} 项 App 安装和更新边界检查通过。`);
