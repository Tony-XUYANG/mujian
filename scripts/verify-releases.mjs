import assert from 'node:assert/strict';
const base=process.env.APP_URL||'http://127.0.0.1:8080';
let checks=0;
async function req(path,method='GET',body,token){const r=await fetch(base+'/api'+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body===undefined?undefined:JSON.stringify(body)});return {status:r.status,data:await r.json()};}
function check(name,ok){assert.ok(ok,name);console.log('PASS '+(++checks)+': '+name);}
const admin=(await req('/auth/login','POST',{username:'admin',password:'Admin123!'})).data.token;
async function account(prefix){return (await req('/auth/register','POST',{username:prefix+Date.now().toString(36),password:'Release123!',nickname:prefix})).data.token;}
const user=await account('预约验收'),follower=await account('追更验收'),other=await account('提醒隔离');
const drama=(await req('/admin/dramas','POST',{title:'排期自动验收',category:'悬疑',description:'验收脚本临时内容',coverImg:'/media/mystery.jpg',videoUrl:'/media/sintel-trailer.mp4'},admin)).data;
const dp='/admin/dramas/'+drama.id,path='/dramas/'+drama.id;
const input=(n,t=Date.now()+3600000)=>({episodeNo:n,title:'预约章节 '+n,videoUrl:drama.videoUrl+'?scheduled='+n,publishAt:t});
const inbox=async(t=user,query='')=>(await req('/me/notifications'+query,'GET',undefined,t)).data;
const planPath=id=>'/admin/release-plans/'+id;
async function create(n,time){const r=await req(dp+'/release-plans','POST',input(n,time),admin);assert.equal(r.status,201,JSON.stringify(r.data));return r.data.find(p=>p.episodeNo===n&&p.status==='SCHEDULED');}
try{
  check('排期日历允许游客访问',(await req('/release-plans')).status===200);
  check('游客不能查看个人预约',(await req('/me/reservations')).status===401);
  check('游客不能读消息信箱',(await req('/me/notifications')).status===401);
  check('普通用户不能排期',(await req(dp+'/release-plans','POST',input(2),user)).status===403);
  check('过去的发布时间被拒绝',(await req(dp+'/release-plans','POST',input(2,Date.now()-1),admin)).data.message.includes('晚于现在'));
  check('超过一年的排期被拒绝',(await req(dp+'/release-plans','POST',input(2,Date.now()+366*86400000),admin)).status===400);
  check('非法排期集号被拒绝',(await req(dp+'/release-plans','POST',input(501),admin)).status===400);
  check('非法视频协议被拒绝',(await req(dp+'/release-plans','POST',{...input(2),videoUrl:'javascript:alert(1)'},admin)).status===400);
  const p2=await create(2);
  check('排期未发布时不增加选集目录',(await req(path+'/episodes')).data.length===1);
  const publicPlans=(await req('/release-plans?dramaId='+drama.id)).data;
  check('公开排期不含片源地址',publicPlans.length===1&&!JSON.stringify(publicPlans).includes('scheduled=2')&&!('videoUrl' in publicPlans[0]));
  check('旧详情片源保持已发布首集',(await req(path)).data.videoUrl===drama.videoUrl);
  check('排期自动恢复连载并扩展总集数',(await req(path)).data.seriesStatus==='SERIALIZING'&&(await req(path)).data.totalEpisodes===2);
  check('重复排期被拒绝',(await req(dp+'/release-plans','POST',input(2),admin)).status===409);
  check('直接发集不能抢占排期集号',(await req(dp+'/episodes','POST',input(2),admin)).status===409);
  check('总集数不能小于排期',(await req(dp+'/series','PUT',{status:'SERIALIZING',totalEpisodes:1},admin)).status===400);
  check('存在排期不能标记完结',(await req(dp+'/series','PUT',{status:'COMPLETED',totalEpisodes:2},admin)).status===400);
  check('游客不能预约',(await req('/release-plans/'+p2.id+'/reservation','PUT')).status===401);
  const reservations=await Promise.all(Array.from({length:6},()=>req('/release-plans/'+p2.id+'/reservation','PUT',undefined,user)));
  check('并发重复预约保持一条记录',reservations.every(r=>r.status===200)&&(await req('/me/reservations','GET',undefined,user)).data.length===1);
  check('预约不能更换集号',(await req(planPath(p2.id),'PUT',input(3),admin)).status===409);
  const changed=input(2,Date.now()+7200000);
  await req(planPath(p2.id),'PUT',changed,admin);
  const mine=(await req('/me/reservations','GET',undefined,user)).data[0];
  check('改期保留预约并同步时间',Boolean(mine.reserved)&&mine.publishAt===changed.publishAt);
  await req(path+'/follow','PUT',undefined,user);await req(path+'/follow','PUT',undefined,follower);
  const pub=await Promise.all(Array.from({length:6},()=>req(planPath(p2.id)+'/publish','POST',undefined,admin)));
  const eps=(await req(path+'/episodes')).data;
  check('并发立即发布只生成一个新集',pub.every(r=>r.status===200)&&eps.length===2);
  check('预约与追剧重叠时只生成一条提醒',(await inbox()).total===1&&(await inbox()).unreadCount===1);
  check('只追剧的用户也收到新集提醒',(await inbox(follower)).total===1);
  check('无关联用户收不到提醒',(await inbox(other)).total===0);
  const message=(await inbox()).items[0];
  check('提醒准确关联发布的新集',message.episodeId===eps[1].id&&message.episodeNo===2);
  check('不能把别人提醒标记为已读',(await req('/me/notifications/'+message.id+'/read','PUT',undefined,other)).status===404);
  await req('/me/notifications/'+message.id+'/read','PUT',undefined,user);
  await req('/me/notifications/'+message.id+'/read','PUT',undefined,user);
  check('已读操作幂等且隔离账号',(await inbox()).unreadCount===0&&(await inbox(follower)).unreadCount===1);
  check('已上线排期不再显示在更新日历',(await req('/release-plans?dramaId='+drama.id)).data.length===0);
  check('已上线排期保留在个人预约',(await req('/me/reservations','GET',undefined,user)).data[0].status==='PUBLISHED');
  check('已发布排期不能再次改期',(await req(planPath(p2.id),'PUT',input(2),admin)).status===409);
  check('已发布不能新预约',(await req('/release-plans/'+p2.id+'/reservation','PUT',undefined,other)).status===409);
  const p3=await create(3);
  await req('/release-plans/'+p3.id+'/reservation','PUT',undefined,other);
  await req(planPath(p3.id)+'/cancel','POST',undefined,admin);
  check('取消状态同步到预约列表',(await req('/me/reservations','GET',undefined,other)).data[0].status==='CANCELLED');
  check('已取消排期不能直接发布',(await req(planPath(p3.id)+'/publish','POST',undefined,admin)).status===409);
  const due=Date.now()+2500,p4=await create(4,due);
  await req(planPath(p4.id)+'/cancel','POST',undefined,admin);
  await req(planPath(p3.id),'PUT',input(3,due),admin);
  const deadline=Date.now()+25000;
  while(Date.now()<deadline&&(await req(path+'/episodes')).data.length<3) await new Promise(r=>setTimeout(r,500));
  check('恢复排期后由定时任务自动发布',(await req(path+'/episodes')).data.length===3);
  check('自动发布给保留预约用户生成提醒',(await inbox(other)).items[0]?.episodeNo===3);
  check('已取消的到期计划不会发布',!(await req(path+'/episodes')).data.some(e=>e.episodeNo===4));
  const through=(await inbox()).throughId;
  await req(dp+'/episodes','POST',{episodeNo:4,title:'直接上线',videoUrl:drama.videoUrl},admin);
  check('旧版立即发集入口也通知追剧用户',(await inbox()).items[0].episodeNo===4);
  await req('/me/notifications/read-all','PUT',{throughId:through},user);
  check('全部已读不会吞掉刷新后新增的提醒',(await inbox()).unreadCount===1);
  check('未读筛选只返回未读',(await inbox(user,'?unread=true')).items.length===1);
  const p5=await create(5);
  await req('/release-plans/'+p5.id+'/reservation','PUT',undefined,other);
  await req('/release-plans/'+p5.id+'/reservation','DELETE',undefined,other);
  await req(planPath(p5.id)+'/publish','POST',undefined,admin);
  check('取消预约后不再收到该集提醒',(await inbox(other)).total===1);
  for(let n=6;n<=25;n++) await req(dp+'/episodes','POST',{episodeNo:n,title:'分页章节 '+n,videoUrl:drama.videoUrl},admin);
  const first=await inbox(),second=await inbox(user,'?page=1');
  check('提醒分页不丢失也不重复',first.total===24&&first.items.length===20&&second.items.length===4&&!second.items.some(n=>first.items.some(m=>m.id===n.id)));
  check('非法页码提供中文错误',(await req('/me/notifications?page=-1','GET',undefined,user)).data.message==='页码不正确');
  const latest=first.items[0];
  await req(dp+'/episodes/'+latest.episodeId,'DELETE',undefined,admin);
  check('下架分集自动清理对应提醒',!(await inbox()).items.some(n=>n.id===latest.id));
  await req('/me/notifications/read-all','PUT',{throughId:(await inbox()).throughId},user);
  check('全部已读会更新未读计数',(await req('/me/notifications/count','GET',undefined,user)).data.unreadCount===0);
  const conflictPlan=await create(499);
  await req(planPath(conflictPlan.id)+'/cancel','POST',undefined,admin);
  const race=await Promise.all([req(planPath(conflictPlan.id),'PUT',input(499),admin),req(dp+'/release-plans','POST',input(499),admin)]);
  check('恢复旧排期与新增同集排期并发时仅一个成功',race.filter(r=>r.status===409).length===1&&(await req(dp+'/release-plans','GET',undefined,admin)).data.filter(p=>p.episodeNo===499&&p.status==='SCHEDULED').length===1);
}finally{
  await req(dp,'DELETE',undefined,admin);
  check('删除短剧级联清理排期预约和提醒',(await inbox()).total===0&&(await req('/me/reservations','GET',undefined,user)).data.length===0);
}
console.log(checks+' release API checks passed.');
