import assert from 'node:assert/strict';
const base=process.env.APP_URL||'http://127.0.0.1:8080';
let passed=0;
async function req(path,method='GET',body,token){const r=await fetch(base+'/api'+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body?JSON.stringify(body):undefined});return {status:r.status,data:r.status===204?null:await r.json()};}
function check(name,condition){assert.ok(condition,name);console.log('PASS '+(++passed)+': '+name);}
const admin=(await req('/auth/login','POST',{username:'admin',password:'Admin123!'})).data.token;
const token=(await req('/auth/register','POST',{username:'分集验收'+Date.now().toString(36),password:'Episode123!',nickname:'分集验收'})).data.token;
const other=(await req('/auth/register','POST',{username:'隔离验收'+Date.now().toString(36),password:'Episode123!',nickname:'隔离验收'})).data.token;
const input={title:'分集自动验收',category:'悬疑',description:'临时测试内容',coverImg:'/media/mystery.jpg',videoUrl:'/media/sintel-trailer.mp4'};
const created=await req('/admin/dramas','POST',input,admin),id=created.data.id;
const second=await req('/admin/dramas','POST',{...input,title:'分集隔离验证'},admin),otherId=second.data.id;
const path='/dramas/'+id,adminPath='/admin/dramas/'+id;
try {
  let episodes=(await req(path+'/episodes')).data;
  const first=episodes[0].id;
  check('新增短剧自动生成第1集',episodes.length===1&&episodes[0].episodeNo===1);
  check('游客可读分集列表',(await req(path+'/episodes')).status===200);
  check('游客不能保存进度',(await req(path+'/episodes/'+first+'/progress','PUT',{progressSec:8,durationSec:52})).status===401);
  const ep={episodeNo:3,title:'第三集',videoUrl:input.videoUrl};
  check('普通用户不能管理分集',(await req(adminPath+'/episodes','POST',ep,token)).status===403);
  await req(path+'/follow','PUT',undefined,token);
  const added=await req(adminPath+'/episodes','POST',ep,admin);
  check('后台发布分集并按集号排序',added.status===201&&added.data.map(e=>e.episodeNo).join(',')==='1,3');
  check('重复集号返回中文冲突',(await req(adminPath+'/episodes','POST',ep,admin)).data.message.includes('已有第3集'));
  check('错误视频协议被拒绝',(await req(adminPath+'/episodes','POST',{...ep,episodeNo:2,videoUrl:'javascript:alert(1)'},admin)).status===400);
  check('非法集号被拒绝',(await req(adminPath+'/episodes','POST',{...ep,episodeNo:0},admin)).status===400);
  check('有缺集时禁止完结',(await req(adminPath+'/series','PUT',{status:'COMPLETED',totalEpisodes:3},admin)).status===400);
  check('总集数不能低于现有集号',(await req(adminPath+'/series','PUT',{status:'SERIALIZING',totalEpisodes:2},admin)).status===400);
  episodes=(await req(adminPath+'/episodes','POST',{...ep,episodeNo:2,title:'第二集'},admin)).data;
  const mid=episodes[1].id,last=episodes[2].id;
  check('集齐后允许标记完结',(await req(adminPath+'/series','PUT',{status:'COMPLETED',totalEpisodes:3},admin)).data.seriesStatus==='COMPLETED');
  check('跨剧集号不能写进度',(await req('/dramas/'+otherId+'/episodes/'+mid+'/progress','PUT',{progressSec:8,durationSec:52},token)).status===404);
  check('跨剧集号不能编辑',(await req('/admin/dramas/'+otherId+'/episodes/'+mid,'PUT',ep,admin)).status===404);
  const follows=await Promise.all(Array.from({length:5},()=>req(path+'/follow','PUT',undefined,token)));
  check('并发追剧幂等',follows.every(r=>r.status===200)&&(await req('/me/following','GET',undefined,token)).data.filter(d=>d.id===id).length===1);
  let following=(await req('/me/following','GET',undefined,token)).data.find(d=>d.id===id);
  check('追剧后发布的分集显示新集',following.newEpisodes===2&&following.remainingEpisodes===3);
  await req(path+'/episodes/'+first+'/progress','PUT',{progressSec:12,durationSec:52},token);
  await req(path+'/episodes/'+mid+'/progress','PUT',{progressSec:7,durationSec:52},token);
  episodes=(await req(path+'/episodes','GET',undefined,token)).data;
  check('不同分集进度独立',episodes[0].progressSec===12&&episodes[1].progressSec===7&&episodes[2].progressSec===0);
  check('不同账号进度隔离',(await req(path+'/episodes','GET',undefined,other)).data.every(e=>e.progressSec===0));
  check('重新打开定位最近观看集',(await req(path,'GET',undefined,token)).data.resumeEpisodeId===mid);
  check('旧观看历史兼容分集',(await req('/me/history','GET',undefined,token)).data.find(d=>d.id===id).resumeEpisodeNo===2);
  await req(path+'/episodes/'+mid+'/progress','PUT',{progressSec:999,durationSec:52},token);
  check('进度限制在时长内',(await req(path+'/episodes','GET',undefined,token)).data[1].progressSec===52);
  following=(await req('/me/following','GET',undefined,token)).data.find(d=>d.id===id);
  check('观看后更新新集和剩余计数',following.newEpisodes===1&&following.remainingEpisodes===2);
  await req(path+'/favorite','PUT',undefined,token);
  await req(path+'/follow','DELETE',undefined,token);
  check('取消追剧不影响收藏',(await req(path,'GET',undefined,token)).data.favorited&&!(await req('/me/following','GET',undefined,token)).data.some(d=>d.id===id));
  await req('/me/history/'+id,'DELETE',undefined,token);
  check('删除历史同步清理分集进度',(await req(path+'/episodes','GET',undefined,token)).data.every(e=>e.progressSec===0));
  await req(path+'/episodes/'+last+'/progress','PUT',{progressSec:10,durationSec:52},token);
  await req(adminPath+'/episodes/'+last,'DELETE',undefined,admin);
  check('删除分集清理进度并恢复连载',(await req(path,'GET',undefined,token)).data.seriesStatus==='SERIALIZING'&&!(await req(path,'GET',undefined,token)).data.resumeEpisodeId);
  check('删除最后一条已看分集后清理历史汇总',!(await req('/me/history','GET',undefined,token)).data.some(d=>d.id===id));
  await req(adminPath+'/episodes/'+mid,'DELETE',undefined,admin);
  check('至少保留一集',(await req(adminPath+'/episodes/'+first,'DELETE',undefined,admin)).status===400);
  await req(path+'/follow','PUT',undefined,token);
} finally {await req(adminPath,'DELETE',undefined,admin);await req('/admin/dramas/'+otherId,'DELETE',undefined,admin);}
check('删除整剧级联清理追剧',(await req('/me/following','GET',undefined,token)).data.every(d=>d.id!==id));
check('删除整剧后分集不可访问',(await req(path+'/episodes')).status===404);
console.log(passed+' episode checks passed.');
